const pl = (n: unknown, one: string, few: string, many: string) => {
  const x = Math.abs(Number(n)) % 100;
  const y = x % 10;
  if (x > 10 && x < 20) return many;
  if (y === 1) return one;
  if (y >= 2 && y <= 4) return few;
  return many;
};
